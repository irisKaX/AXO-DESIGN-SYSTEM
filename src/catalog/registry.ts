type Definition = Pick<ComponentDocumentation, 'id' | 'name' | 'category' | 'description' | 'kind' | 'variants' | 'sizes' | 'controls' | 'props' | 'code' | 'source' | 'demo'> & { guidance: string }

function documentComponent({ guidance, ...entry }: Definition): ComponentDocumentation {
  const interactive = entry.controls.length > 0 || ['Buttons & Actions', 'Navigation', 'Overlays'].includes(entry.category)
  const popup = entry.category === 'Overlays' || ['accordion', 'collapsible', 'navigation-menu', 'dropdown-menu', 'context-menu', 'menubar'].includes(entry.id)
  return {
    ...entry,
    states: ['Default', ...(interactive ? ['Hover', 'Focus Visible', 'Active / Pressed'] : []), ...entry.controls, ...(popup ? ['Open / Closed'] : [])],
    usage: {
      recommended: [guidance, 'Používejte veřejné exporty z @/design-system.'],
      avoid: ['Nekopírujte implementaci do katalogu nebo aplikace.', 'Nepoužívejte vizuální stav jako náhradu skutečné funkčnosti.'],
    },
    accessibility: {
      semantics: [guidance],
      keyboard: ['Interaktivní prvky jsou dostupné přes Tab; sledujte viditelný focus.', ...(['Navigation', 'Overlays'].includes(entry.category) || ['select', 'calendar', 'radio-group', 'slider'].includes(entry.id) ? ['Nabídky a výběry ovládejte šipkami; Escape zavírá popup.'] : [])],
      labeling: ['Buttons & Actions', 'Inputs & Forms', 'Overlays'].includes(entry.category) ? ['Každé pole a ikonová akce potřebuje přístupný název.', 'Chyby a změny stavu doplňujte srozumitelným textem.'] : ['Význam obsahu musí být srozumitelný i bez barvy.'],
    },
  }
}

